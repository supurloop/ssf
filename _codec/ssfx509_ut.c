        SSF_ASSERT(SSFX509VerifyChain(chain, chainLens, 1,
                   trust, trustLens, 1, "other.local", validTime) == false);

        /* 8d. Case-insensitive: "TEST.SSF.LOCAL" */
        SSF_ASSERT(SSFX509VerifyChain(chain, chainLens, 1,
                   trust, trustLens, 1, "TEST.SSF.LOCAL", validTime) == true);

