#!/bin/sh
# Converts the DER files that gen.sh and gen_modeled.pl produced into ../ssfcms_ut_fix.h, one
# static const uint8_t array per fixture. Run gen.sh, then gen_modeled.pl, then this.
cd "$(dirname "$0")/out" || exit 1
emit() {
  name=$1; file=$2
  printf '/* %s: %s bytes */\n' "$(basename "$file")" "$(wc -c < "$file")"
  printf 'static const uint8_t %s[] = {\n' "$name"
  od -An -v -tx1 "$file" | tr -s ' \n' '\n\n' | grep -v '^$' | awk '{ printf "%s0x%su,", (n%12==0 ? "    " : " "), toupper($1); n++; if (n%12==0) printf "\n" } END { if (n%12!=0) printf "\n" }'
  printf '};\n\n'
}
{
printf '/* Generated by ssfcms_ut_fixtures/toc.sh from gen.sh and gen_modeled.pl output (OpenSSL 3.2) */\n\n'
emit _utFixContent content.bin
emit _utFixRootDer root.der
emit _utFixIntDer int.der
emit _utFixRsaDer rsa.der
emit _utFixEdDer ed.der
emit _utFixOtherDer other.der
emit _utFixEcdsaChainDetached ecdsa_chain_detached.der
emit _utFixEcdsaChainDetachedBer ecdsa_chain_detached_ber.der
emit _utFixEcdsaCsSha384Detached ecdsa_cs_sha384_detached.der
emit _utFixEcdsaNoattrAttached ecdsa_noattr_attached.der
emit _utFixEcdsaSkidAttached ecdsa_skid_attached.der
emit _utFixRsaPkcs1Detached rsa_pkcs1_detached.der
emit _utFixRsaPssDetached rsa_pss_detached.der
emit _utFixTwoSignersDetached two_signers_detached.der
emit _utFixRsaChainDetached rsa_chain_detached.der
[ -s ed25519_detached.der ] && emit _utFixEd25519Detached ed25519_detached.der
printf '/* Modeled firmware signature: see gen_modeled.pl, assembled around OpenSSL outputs. */\n\n'
emit _utFixFwContent ../modeled/fw.bin
emit _utFixModRootDer ../modeled/root.der
emit _utFixModFscaDer ../modeled/fsca.der
emit _utFixModFmDer ../modeled/fm.der
emit _utFixModeledCms ../modeled/modeled.der
} > ../../ssfcms_ut_fix.h
wc -l -c ../../ssfcms_ut_fix.h
awk 'length > 100 {print "long line " NR}' ../../ssfcms_ut_fix.h | head -3
