    /* ---- AKID/SKID with RFC 7093 SHA-2 keyIdentifier sizes ---- */
    /* Exercises the encoder paths that previously had:                                          */
    /*   - unbounded memcpy into a 32-byte akidSeqBuf stack buffer (stack overflow for akidLen   */
    /*     > 30)                                                                                  */
    /*   - single-byte `(uint8_t)akidLen` DER length truncation (invalid DER for akidLen > 127)  */
    /*   - silent truncation in innerOctetBuf[32] for skidLen > 30                                */
    /* Each boundary length is encoded, parsed, and verified to round-trip intact.                */
    {
        uint8_t privKey[SSF_ECDSA_MAX_PRIV_KEY_SIZE];
        uint8_t pubKey[SSF_ECDSA_MAX_PUB_KEY_SIZE];
        size_t pubKeyLen;
        uint8_t serial[] = { 0x44u };
        uint32_t idx;
        /* KeyIdentifier payloads of varying lengths — each filled with a deterministic pattern */
        /* so round-trip equality can be asserted per-byte.                                      */
        static uint8_t kidBuf[64];

        for (idx = 0; idx < sizeof(kidBuf); idx++)
        {
            kidBuf[idx] = (uint8_t)((idx * 7u) ^ 0xA5u);
        }

        memset(privKey, 0, sizeof(privKey));
        SSF_ASSERT(SSFECDSAKeyGen(SSF_EC_CURVE_P256, privKey, sizeof(privKey),
                                   pubKey, sizeof(pubKey), &pubKeyLen) == true);

        /* Build a cert with AKID+SKID of the given length, parse it, and compare the parsed   */
        /* keyIdentifiers byte-for-byte against the input. Lengths at 20/32/48/64 cover         */
        /* SHA-1, SHA-256, SHA-384, SHA-512 keyIdentifier choices (RFC 5280 / RFC 7093).         */
        #define _KID_ROUND_TRIP(_kidLen) do { \
            SSFX509GenParams_t p; \
            uint8_t tbsDer[512]; \
            uint32_t tbsLen; \
            uint8_t tbsHash[32]; \
            uint8_t sig[SSF_ECDSA_MAX_SIG_SIZE]; \
            size_t sigLen; \
            uint8_t certDer[SSF_X509_CONFIG_MAX_CERT_SIZE]; \
            uint32_t certDerLen; \
            SSFX509Cert_t parsed; \
            memset(&p, 0, sizeof(p)); \
            p.pathLenConstraint = -1; \
            p.version = 2u; \
            p.serial = serial; \
            p.serialLen = sizeof(serial); \
            p.sigAlgOidRaw = _utSigAlgOid; \
            p.sigAlgOidRawLen = sizeof(_utSigAlgOid); \
            p.issuer.cn = "kid.test"; \
            p.subject.cn = "kid.test"; \
            p.notBefore = 1700000000ull; \
            p.notAfter = 2000000000ull; \
            p.pubKeyAlgOidRaw = _utPubKeyAlgOid; \
            p.pubKeyAlgOidRawLen = sizeof(_utPubKeyAlgOid); \
            p.ecCurveOidRaw = _utCurveOid; \
            p.ecCurveOidRawLen = sizeof(_utCurveOid); \
            p.pubKey = pubKey; \
            p.pubKeyLen = (uint32_t)pubKeyLen; \
            p.skid = kidBuf; \
            p.skidLen = (_kidLen); \
            p.akid = kidBuf; \
            p.akidLen = (_kidLen); \
            tbsLen = SSFX509EncodeTBS(tbsDer, sizeof(tbsDer), &p); \
            SSF_ASSERT(tbsLen > 0u); \
            SSFSHA256(tbsDer, tbsLen, tbsHash, sizeof(tbsHash)); \
            SSF_ASSERT(SSFECDSASign(SSF_EC_CURVE_P256, privKey, 32, tbsHash, 32, \
                                     sig, sizeof(sig), &sigLen) == true); \
            certDerLen = SSFX509EncodeCert(certDer, sizeof(certDer), &p, sig, \
                                            (uint32_t)sigLen); \
            SSF_ASSERT(certDerLen > 0u); \
            SSF_ASSERT(SSFX509Parse(certDer, certDerLen, &parsed) == true); \
            SSF_ASSERT(parsed.skidLen == (_kidLen)); \
            SSF_ASSERT(memcmp(parsed.skid, kidBuf, (_kidLen)) == 0); \
            SSF_ASSERT(parsed.akidLen == (_kidLen)); \
            SSF_ASSERT(memcmp(parsed.akid, kidBuf, (_kidLen)) == 0); \
        } while (0)

        /* 20 bytes — SHA-1 baseline (RFC 5280 §4.2.1.2 default). Regression guard. */
        _KID_ROUND_TRIP(20u);

        /* 30 bytes — just under the old 32-byte buffer ceiling. Used to work. */
        _KID_ROUND_TRIP(30u);

        /* 32 bytes — SHA-256 keyIdentifier (RFC 7093). This would have:                        */
        /*   - overflowed the old akidSeqBuf[32] by 2 bytes,                                    */
        /*   - silently truncated the SKID to empty via innerOctetBuf[32].                      */
        _KID_ROUND_TRIP(32u);

        /* 48 bytes — SHA-384 keyIdentifier. Old AKID: 16-byte stack overflow. */
        _KID_ROUND_TRIP(48u);

        /* 64 bytes — SHA-512 keyIdentifier. Maximum supported by the new buffers.              */
        /* AKID length 64 also crosses the DER single-byte-length threshold (64 < 128 so still  */
        /* single-byte, but the test still exercises SSFASN1EncTagLen for consistency).          */
        _KID_ROUND_TRIP(64u);

        /* Over-limit: 65-byte AKID/SKID. Encoder must refuse (return 0) rather than overflow.  */
        {
            SSFX509GenParams_t p;
            uint8_t tbsDer[512];
            memset(&p, 0, sizeof(p));
            p.pathLenConstraint = -1;
            p.version = 2u;
            p.serial = serial;
            p.serialLen = sizeof(serial);
            p.sigAlgOidRaw = _utSigAlgOid;
            p.sigAlgOidRawLen = sizeof(_utSigAlgOid);
            p.issuer.cn = "kid.test";
            p.subject.cn = "kid.test";
            p.notBefore = 1700000000ull;
            p.notAfter = 2000000000ull;
            p.pubKeyAlgOidRaw = _utPubKeyAlgOid;
            p.pubKeyAlgOidRawLen = sizeof(_utPubKeyAlgOid);
            p.ecCurveOidRaw = _utCurveOid;
            p.ecCurveOidRawLen = sizeof(_utCurveOid);
            p.pubKey = pubKey;
            p.pubKeyLen = (uint32_t)pubKeyLen;
            p.akid = kidBuf;
            p.akidLen = 65u;  /* > _UT_KID_MAX */
            SSF_ASSERT(SSFX509EncodeTBS(tbsDer, sizeof(tbsDer), &p) == 0u);

            /* Same for SKID alone. */
            p.akid = NULL;
            p.akidLen = 0u;
            p.skid = kidBuf;
            p.skidLen = 65u;
            SSF_ASSERT(SSFX509EncodeTBS(tbsDer, sizeof(tbsDer), &p) == 0u);
        }

        #undef _KID_ROUND_TRIP
    }

