    /* Check not-yet-valid */
    SSF_ASSERT(SSFX509IsValid(&cert, cert.notBefore - 1u) == false);

    /* ---- Public key: EC P-256 ---- */
    SSF_ASSERT(SSFX509IsP256(&cert) == true);
    SSF_ASSERT(cert.pubKey != NULL);
    SSF_ASSERT(cert.pubKeyLen == 65u); /* Uncompressed P-256 point: 04 || X(32) || Y(32) */
    SSF_ASSERT(cert.pubKey[0] == 0x04u); /* Uncompressed point indicator */

